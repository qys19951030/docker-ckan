#!/bin/bash
#
# verify_secrets.sh
#
# Reproducible verification of the CKAN session/JWT secret resolution logic
# from start_ckan.sh.  This script extracts and runs the resolve_secret
# helper (exactly as it appears in images/ckan/*/setup/app/start_ckan.sh)
# against every combination of env-var inputs we care about, and prints
# PASS / FAIL for each case.
#
# It also prints step-by-step instructions for an end-to-end verification
# using docker-compose (see the "E2E_VERIFICATION" section at the bottom).
#
set -u

PASS=0
FAIL=0

pass() { echo "  [PASS] $1"; PASS=$((PASS+1)); }
fail() { echo "  [FAIL] $1  (got: '$2')"; FAIL=$((FAIL+1)); }

# ---------------------------------------------------------------------------
# Exact copy of resolve_secret from images/ckan/*/setup/app/start_ckan.sh
# KEEP THIS SYNCHRONISED when editing the startup scripts.
# ---------------------------------------------------------------------------
resolve_secret() {
	local envvar_ckanstyle="$1"
	local envvar_legacy="$2"
	local val=""
	if [[ -n "${!envvar_ckanstyle+x}" && -n "${!envvar_ckanstyle}" ]]; then
		val="${!envvar_ckanstyle}"
	elif [[ -n "${!envvar_legacy+x}" && -n "${!envvar_legacy}" ]]; then
		val="${!envvar_legacy}"
	fi
	if [[ "$val" == string:* ]]; then
		val="${val#string:}"
	fi
	if [[ "$val" == "CHANGE_ME" ]]; then
		val=""
	fi
	echo "$val"
}

run_test() {
	local desc="$1"
	local expected="$2"
	unset CKAN___TEST BEAKER_TEST
	# shellcheck disable=SC2015
	[[ $# -ge 3 && -n "$3" ]] && export CKAN___TEST="$3" || true
	# shellcheck disable=SC2015
	[[ $# -ge 4 && -n "$4" ]] && export BEAKER_TEST="$4" || true

	local actual
	actual="$(resolve_secret CKAN___TEST BEAKER_TEST)"
	if [[ "$actual" == "$expected" ]]; then
		pass "$desc"
	else
		fail "$desc" "$actual"
	fi
	unset CKAN___TEST BEAKER_TEST
}

echo "============================================================"
echo " Unit tests – resolve_secret() from start_ckan.sh"
echo "============================================================"

echo
echo "-- Path A: secrets PROVIDED via env (must be preserved) --"

run_test \
	"CKAN___ style (no prefix)" \
	"my-beaker-secret" \
	"my-beaker-secret" \
	""

run_test \
	"CKAN___ style with string: prefix (prefix stripped)" \
	"my-jwt-secret" \
	"string:my-jwt-secret" \
	""

run_test \
	"Legacy BEAKER_ style used when CKAN___ style absent" \
	"legacy-secret" \
	"" \
	"legacy-secret"

run_test \
	"CKAN___ style takes precedence over legacy" \
	"ckanstyle-wins" \
	"ckanstyle-wins" \
	"legacy-ignored"

run_test \
	"CKAN___ style with string:CHANGE_ME -> treated as empty (auto-gen path)" \
	"" \
	"string:CHANGE_ME" \
	""

echo
echo "-- Path B: secrets NOT provided -> must be empty (trigger auto-gen) --"

run_test \
	"Both vars UNSET" \
	""

run_test \
	"CKAN___ exactly 'CHANGE_ME' -> treated as empty" \
	"" \
	"CHANGE_ME" \
	""

run_test \
	"Legacy exactly 'CHANGE_ME' -> treated as empty" \
	"" \
	"" \
	"CHANGE_ME"

echo
echo "============================================================"
echo " Result: $PASS passed, $FAIL failed"
echo "============================================================"
[[ $FAIL -eq 0 ]] || exit 1

# ---------------------------------------------------------------------------
# End-to-end verification instructions using docker-compose.
# ---------------------------------------------------------------------------
cat <<'E2E_VERIFICATION'

